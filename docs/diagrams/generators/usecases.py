a.act("rekey", "streams", "Re-key the event by its category")
a.act("count", "streams", "Add one to that category's count")
a.store("store", "streams", "jobs-per-category-store")
a.start("s2", "op").act("open", "op", "Open the Live analytics tab")
a.dec("ready", "api", "State store ready to query?")
a.act("q", "api", "Read every category and count from the store")
a.act("fallback", "api", "Read the in-memory counters instead")
a.act("ret", "api", "Return the counts")
a.act("see", "op", "See a bar per category, refreshed every 5 seconds").end("e", "op")
a.to("s", "pub").to("pub", "read", "Kafka", "dashed").to("read", "hascat")
a.to("hascat", "skip", "no").to("skip", "ex").to("hascat", "rekey", "yes").flow("rekey", "count", "store")
a.flow("s2", "open", "ready")
a.to("ready", "q", "yes").to("ready", "fallback", "no").to("q", "ret").to("fallback", "ret")
