a.act("tool", "match", "Run listOpenJobs or findJobsByCategory on the JobSnapshots")
a.act("rank", "llm", "Rank the jobs and reply in JSON")
a.dec("usable", "match", "Call succeeded and reply readable?")
a.act("check", "match", "Drop jobs that are not on the board, limit the scores, keep the best 5")
a.act("rule", "match", "Use the rule-based SkillMatcher instead")
a.act("ret", "match", "Return the recommendations and where they came from")
a.act("see", "student", "See the jobs, each with a score and a reason").end("e", "student")
a.flow("s", "ask", "conf")
a.to("conf", "err", "no: 503").to("conf", "prof", "yes").to("prof", "err", "no: 404").to("prof", "build", "yes")
a.to("err", "ex")
a.flow("build", "think", "tool", "rank", "usable")
a.to("usable", "check", "yes").to("usable", "rule", "no").to("check", "ret").to("rule", "ret")
a.flow("ret", "see", "e")
diagrams.append(a)

