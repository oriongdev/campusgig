"""The 14 use cases of CampusGig as UML activity diagrams. Run: python3 usecases.py <out dir>"""
import os, subprocess, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from activity import Activity

def A(n, title):
    return Activity(f"uc{n:02d}", f"UC{n}  {title}")

diagrams = []

# ---- UC1 -----------------------------------------------------------------------------------
a = A(1, "Student registers a profile")
a.lane("student", "Student", "actor").lane("user", "user-service").lane("match", "matching-service", "other")
a.start("s", "student").act("fill", "student", "Enter name, email, skills and availability")
a.dec("valid", "user", "Name and email valid?").dec("dup", "user", "Email already registered?")
a.act("err", "user", "Return the error with its reason").end("ex", "user")
a.act("save", "user", "Normalise the skills and save the Student")
a.send("pub", "user", "Publish StudentProfileUpdated").act("ok", "user", "Return 201 with the profile")
a.recv("snap", "match", "Store a StudentSnapshot for matching")
a.act("see", "student", "See the new profile").end("e", "student")
a.flow("s", "fill", "valid")
a.to("valid", "err", "no: 400").to("valid", "dup", "yes")
a.to("dup", "err", "yes: 409").to("dup", "save", "no")
a.flow("save", "pub", "ok", "see", "e").to("err", "ex").to("pub", "snap", "Kafka", "dashed")
diagrams.append(a)

