if __name__ == "__main__":
    out = sys.argv[1]
    os.makedirs(os.path.join(out, "src"), exist_ok=True)
    for d in diagrams:
        src = os.path.join(out, "src", d.name + ".dot")
        open(src, "w").write(d.dot() + "\n")
        subprocess.run(["dot", "-Tpng", "-Gdpi=160", src, "-o", os.path.join(out, d.name + ".png")], check=True)
        subprocess.run(["dot", "-Tsvg", src, "-o", os.path.join(out, d.name + ".svg")], check=True)
    print(len(diagrams), "diagrams written to", out)
