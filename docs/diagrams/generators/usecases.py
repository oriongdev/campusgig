# ---- UC12 ----------------------------------------------------------------------------------
a = A(12, "Real-time analysis: applications per job and trending jobs")
a.lane("app", "application-service").lane("streams", "matching-service: Kafka Streams", "other").lane("api", "matching-service: REST").lane("op", "Platform operator", "actor")
a.start("s", "app").send("pub", "app", "Publish ApplicationSubmitted")
a.recv("read", "streams", "Read the event from the application-submitted topic")
a.act("rekey", "streams", "Re-key the event by job id")
a.bar("fork", "streams")
a.act("total", "streams", "Add one to the job's total")
a.act("window", "streams", "Add one to the job's count for the current 15-minute window")
a.store("tstore", "streams", "applications-per-job-store").store("wstore", "streams", "trending-jobs-store")
a.start("s2", "op").act("open", "op", "Open the Live analytics tab")
a.act("q1", "api", "Read every job's total from the store")
a.act("q2", "api", "Read the windows that started in the last 15 minutes")
a.act("keep", "api", "Keep jobs with 2 or more applications and add their titles")
a.act("ret", "api", "Return the totals and the trending jobs")
a.act("see", "op", "See applications per job and the jobs marked trending").end("e", "op")
a.to("s", "pub").to("pub", "read", "Kafka", "dashed").flow("read", "rekey", "fork")
a.to("fork", "total").to("fork", "window").to("total", "tstore").to("window", "wstore")
a.flow("s2", "open", "q1", "q2", "keep", "ret", "see", "e")
a.to("tstore", "q1", "interactive query", "dashed").to("wstore", "q2", "interactive query", "dashed")
diagrams.append(a)

# ---- UC13 ----------------------------------------------------------------------------------
a = A(13, "AI matching agent recommends jobs to a student")
a.lane("student", "Student", "actor").lane("match", "matching-service").lane("llm", "Gemini (LLM)", "llm")
a.start("s", "student").act("ask", "student", "Choose Ask the AI agent")
